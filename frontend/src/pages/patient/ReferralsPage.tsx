import React, { useEffect, useState } from 'react';
import { ShieldCheck, User, Calendar, AlertCircle, Clock, CheckCircle2, XCircle, ArrowRight, Stethoscope } from 'lucide-react';
import api from '../../services/api';

export const ReferralsPage: React.FC<{ patientId?: string }> = ({ patientId }) => {
  const [referrals, setReferrals] = useState<any[]>([]);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    const fetchReferrals = async () => {
      setLoading(true);
      try {
        const url = patientId ? `/referrals/patient/${patientId}` : '/referrals';
        const res = await api.get(url);
        setReferrals(res.data);
      } catch (err) {
        console.error('Failed to load referrals:', err);
      } finally {
        setLoading(false);
      }
    };

    fetchReferrals();
  }, [patientId]);

  const getPriorityBadge = (priority: string) => {
    switch (priority) {
      case 'EMERGENCY':
        return {
          bg: '#fee2e2',
          color: '#dc2626',
          border: '#fca5a5',
          label: '🔴 Emergency (Immediate)',
        };
      case 'URGENT':
        return {
          bg: '#fef3c7',
          color: '#d97706',
          border: '#fde68a',
          label: '🟠 Urgent (24-48h)',
        };
      default:
        return {
          bg: '#ecfdf5',
          color: '#059669',
          border: '#a7f3d0',
          label: '🟢 Routine Review',
        };
    }
  };

  const getStatusBadge = (status: string) => {
    switch (status) {
      case 'COMPLETED':
        return { bg: '#ecfdf5', color: '#047857', border: '#a7f3d0', icon: <CheckCircle2 size={13} /> };
      case 'ACCEPTED':
        return { bg: '#eff6ff', color: '#1d4ed8', border: '#bfdbfe', icon: <Clock size={13} /> };
      case 'REJECTED':
        return { bg: '#fef2f2', color: '#b91c1c', border: '#fecaca', icon: <XCircle size={13} /> };
      default:
        return { bg: '#fffbeb', color: '#b45309', border: '#fde68a', icon: <AlertCircle size={13} /> };
    }
  };

  return (
    <div>
      <div style={{ marginBottom: '1.25rem' }}>
        <h3 style={{ fontSize: '1.3rem', fontWeight: 800, color: 'var(--text-main)', display: 'flex', alignItems: 'center', gap: '0.6rem', margin: 0 }}>
          <ShieldCheck size={22} color="var(--primary-600)" /> Cross-Specialty Clinical Referrals
        </h3>
        <p style={{ fontSize: '0.86rem', color: 'var(--text-muted)', margin: '0.25rem 0 0 0' }}>
          Consultation referrals generated by your physicians to super-specialists with automated triage urgency tracking.
        </p>
      </div>

      {loading ? (
        <div className="card" style={{ textAlign: 'center', padding: '3rem', color: 'var(--text-muted)' }}>
          Loading specialist referrals...
        </div>
      ) : referrals.length === 0 ? (
        <div className="card" style={{ textAlign: 'center', padding: '3rem 1.5rem', background: '#f8fafc', border: '1px dashed #cbd5e1', borderRadius: 14 }}>
          <Stethoscope size={36} color="#94a3b8" style={{ margin: '0 auto 0.75rem auto' }} />
          <h4 style={{ fontSize: '1.05rem', fontWeight: 700, color: '#334155', margin: '0 0 0.35rem 0' }}>
            No Cross-Specialty Referrals Active
          </h4>
          <p style={{ fontSize: '0.85rem', color: '#64748b', maxWidth: 450, margin: '0 auto' }}>
            When your primary doctor refers you to a specialist (Cardiology, Neurology, Oncology, etc.), the referral details, triage priority, and specialist notes will appear here.
          </p>
        </div>
      ) : (
        <div style={{ display: 'grid', gridTemplateColumns: 'repeat(auto-fit, minmax(min(100%, 340px), 1fr))', gap: '1rem' }}>
          {referrals.map((ref) => {
            const prio = getPriorityBadge(ref.priority);
            const stat = getStatusBadge(ref.status);

            return (
              <div
                key={ref.id}
                className="card"
                style={{
                  padding: '1.25rem',
                  borderRadius: 14,
                  border: '1px solid var(--border-light)',
                  boxShadow: '0 2px 8px rgba(15,23,42,0.04)',
                  display: 'flex',
                  flexDirection: 'column',
                  justifyContent: 'space-between',
                  gap: '0.85rem',
                }}
              >
                <div>
                  <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'flex-start', gap: '0.5rem', marginBottom: '0.65rem' }}>
                    <div style={{ display: 'flex', alignItems: 'center', gap: '0.4rem', flexWrap: 'wrap' }}>
                      <span
                        style={{
                          background: '#f3e8ff',
                          color: '#7e22ce',
                          border: '1px solid #e9d5ff',
                          fontSize: '0.74rem',
                          fontWeight: 800,
                          padding: '0.2rem 0.6rem',
                          borderRadius: 999,
                          textTransform: 'uppercase',
                        }}
                      >
                        {ref.targetSpecialty}
                      </span>
                      <span
                        style={{
                          background: prio.bg,
                          color: prio.color,
                          border: `1px solid ${prio.border}`,
                          fontSize: '0.72rem',
                          fontWeight: 800,
                          padding: '0.2rem 0.55rem',
                          borderRadius: 999,
                        }}
                      >
                        {prio.label}
                      </span>
                    </div>

                    <span
                      style={{
                        background: stat.bg,
                        color: stat.color,
                        border: `1px solid ${stat.border}`,
                        fontSize: '0.72rem',
                        fontWeight: 800,
                        padding: '0.2rem 0.55rem',
                        borderRadius: 999,
                        display: 'inline-flex',
                        alignItems: 'center',
                        gap: '0.3rem',
                      }}
                    >
                      {stat.icon} {ref.status}
                    </span>
                  </div>

                  <h4 style={{ fontSize: '1rem', fontWeight: 800, color: 'var(--text-main)', margin: '0 0 0.4rem 0', lineHeight: 1.35 }}>
                    {ref.reason}
                  </h4>

                  <div style={{ background: '#f8fafc', padding: '0.75rem', borderRadius: 10, border: '1px solid #e2e8f0', fontSize: '0.8rem', display: 'flex', flexDirection: 'column', gap: '0.35rem' }}>
                    <div>
                      <span style={{ color: '#64748b' }}>Referring Doctor: </span>
                      <strong style={{ color: '#0f172a' }}>{ref.referringDoctor?.user?.name || 'Primary Physician'}</strong>{' '}
                      <span style={{ color: '#64748b', fontSize: '0.75rem' }}>({ref.referringDoctor?.specialty || 'General Practice'})</span>
                    </div>

                    {ref.clinicalNotes && (
                      (() => {
                        const hasResolution = ref.clinicalNotes.includes('Resolution:');
                        if (hasResolution) {
                          const parts = ref.clinicalNotes.split(/\|\s*Resolution:\s*|Resolution:\s*/);
                          const referringNotes = parts[0]?.trim();
                          const resNotes = parts[1]?.trim() || (ref.clinicalNotes.startsWith('Resolution:') ? ref.clinicalNotes.replace(/^Resolution:\s*/, '') : '');
                          return (
                            <>
                              {referringNotes && (
                                <div style={{ color: '#334155', borderTop: '1px dashed #cbd5e1', paddingTop: '0.35rem', marginTop: '0.2rem', lineHeight: 1.4 }}>
                                  <span style={{ fontWeight: 700, color: '#0369a1' }}>Referring Clinical Notes: </span>
                                  {referringNotes}
                                </div>
                              )}
                              {resNotes && (
                                <div style={{ background: '#ecfdf5', color: '#065f46', border: '1px solid #a7f3d0', borderRadius: 8, padding: '0.5rem 0.65rem', marginTop: '0.4rem', lineHeight: 1.4, fontSize: '0.8rem' }}>
                                  <span style={{ fontWeight: 800, color: '#047857', display: 'flex', alignItems: 'center', gap: '0.3rem', marginBottom: '0.15rem' }}>
                                    <CheckCircle2 size={13} color="#059669" /> Specialist Resolution Notes:
                                  </span>
                                  {resNotes}
                                </div>
                              )}
                            </>
                          );
                        }
                        return (
                          <div style={{ color: '#334155', borderTop: '1px dashed #cbd5e1', paddingTop: '0.35rem', marginTop: '0.2rem', lineHeight: 1.4 }}>
                            <span style={{ fontWeight: 700, color: '#0369a1' }}>Clinical Notes: </span>
                            {ref.clinicalNotes}
                          </div>
                        );
                      })()
                    )}
                  </div>
                </div>

                <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', fontSize: '0.74rem', color: 'var(--text-muted)', borderTop: '1px solid #f1f5f9', paddingTop: '0.65rem' }}>
                  <span>Referral ID: #{ref.id.slice(0, 8)}</span>
                  <span>{new Date(ref.createdAt).toLocaleDateString()}</span>
                </div>
              </div>
            );
          })}
        </div>
      )}
    </div>
  );
};
